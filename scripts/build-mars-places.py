#!/usr/bin/env python3
"""
Builds blue_modules/mars-places-data.js: contour lines of 24 named places on Mars, for the civic ID card.

Source: NASA Mars Global Surveyor MOLA MEGDR, 16 pixels per degree, public domain:
  https://pds-geosciences.wustl.edu/mgs/mgs-m-mola-5-megdr-l3-v1/mgsl_300x/meg016/megt90n000eb.img  (33 MB)

  python3 scripts/build-mars-places.py /path/to/megt90n000eb.img > blue_modules/mars-places-data.js

Needs numpy, scipy and matplotlib. A citizen's place is chosen from their civic address (blue_modules/mars-places.js)
by its position in this list, so THE LIST IS PERMANENT: adding, removing or reordering places would move every citizen.
Redrawing the maps (levels, tolerance) is fine.
"""
import sys
import numpy as np
from scipy.ndimage import gaussian_filter, zoom
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

# name, latitude (north +), longitude (east, 0-360), width of the view in degrees of longitude
PLACES = [
    ("Jezero Crater", 18.38, 77.58, 3.0), ("Gale Crater", -5.4, 137.8, 3.5), ("Olympus Mons", 18.65, 226.2, 16),
    ("Melas Chasma", -10.5, 287.0, 8), ("Arsia Mons", -8.26, 239.9, 9), ("Pavonis Mons", 1.48, 247.0, 7),
    ("Ascraeus Mons", 11.8, 255.5, 8), ("Elysium Mons", 25.0, 147.2, 8), ("Noctis Labyrinthus", -6.9, 258.0, 8),
    ("Candor Chasma", -6.5, 289.0, 7), ("Hebes Chasma", -1.1, 283.9, 5), ("Gusev Crater", -14.5, 175.4, 4),
    ("Holden Crater", -26.4, 326.0, 4), ("Eberswalde Crater", -23.9, 326.7, 2.5), ("Mawrth Vallis", 22.6, 343.5, 5),
    ("Nili Fossae", 22.0, 75.0, 6), ("Kasei Valles", 24.6, 294.6, 10), ("Ares Vallis", 10.3, 334.4, 6),
    ("Tharsis Tholus", 13.4, 269.2, 4), ("Apollinaris Mons", -9.3, 174.4, 5), ("Hale Crater", -35.7, 323.4, 6),
    ("Huygens Crater", -13.9, 55.6, 7), ("Schiaparelli Crater", -2.7, 16.7, 8), ("Ius Chasma", -7.0, 274.7, 7),
]
W, H = 640, 500      # the map's box; the card shows it with "slice"
SPOT_Y = 0.4         # the place sits 40% down the box, above the name on the card
LEVELS, MAJOR_EVERY = 16, 4
TOLERANCE = 1.2      # Douglas-Peucker tolerance, in box units


def simplify(points, tol):
    if len(points) < 3:
        return points
    start, end = points[0], points[-1]
    line = end - start
    norm = np.hypot(*line)
    rel = points - start
    dist = np.abs(line[0] * rel[:, 1] - line[1] * rel[:, 0]) / norm if norm else np.hypot(rel[:, 0], rel[:, 1])
    i = int(np.argmax(dist))
    if dist[i] <= tol:
        return np.array([start, end])
    return np.vstack([simplify(points[: i + 1], tol)[:-1], simplify(points[i:], tol)])


def encode(segments):
    out = []
    for seg in segments:
        pts = np.round(seg).astype(int)
        keep = [pts[0]] + [p for a, p in zip(pts, pts[1:]) if (p != a).any()]
        if len(keep) < 3:
            continue
        x, y = keep[0]
        deltas = " ".join(f"{int(b[0] - a[0])} {int(b[1] - a[1])}" for a, b in zip(keep, keep[1:]))
        out.append(f"M{x} {y}l{deltas}")
    return "".join(out).replace(" -", "-")


def place_paths(dem, lat, lon, wdeg):
    hdeg = wdeg * np.cos(np.radians(lat)) * H / W
    top, bottom = lat + hdeg * SPOT_Y, lat - hdeg * (1 - SPOT_Y)
    r0, r1 = int((90 - top) * 16), int((90 - bottom) * 16) + 1
    c0, c1 = int((lon - wdeg / 2) * 16), int((lon + wdeg / 2) * 16) + 1
    z = gaussian_filter(zoom(np.array(dem[r0:r1, c0:c1], dtype=float), 6, order=3), 2.5)
    lo, hi = np.percentile(z, 1), np.percentile(z, 99.5)
    xs = np.arange(z.shape[1]) * W / (z.shape[1] - 1)
    ys = np.arange(z.shape[0]) * H / (z.shape[0] - 1)
    cs = plt.contour(xs, ys, z, levels=np.linspace(lo, hi, LEVELS))
    major, minor = [], []
    for i, segs in enumerate(cs.allsegs):
        for seg in segs:
            if len(seg) < 4 or np.hypot(*np.ptp(seg, axis=0)) < 14:  # drop specks
                continue
            (major if i % MAJOR_EVERY == 0 else minor).append(simplify(np.asarray(seg), TOLERANCE))
    plt.close("all")
    return encode(major), encode(minor)


def main():
    dem = np.memmap(sys.argv[1], dtype=">i2", mode="r", shape=(2880, 5760))
    rows = []
    for name, lat, lon, wdeg in PLACES:
        major, minor = place_paths(dem, lat, lon, wdeg)
        rows.append(f"  {{ name: {name!r}, lat: {lat}, lon: {lon}, major: '{major}', minor: '{minor}' }},")
        print(f"{name}: {len(major) + len(minor)} bytes", file=sys.stderr)
    print("// Generated by scripts/build-mars-places.py from NASA's MOLA elevation data (public domain). Do not edit by hand.")
    print("// The list is permanent: a citizen's place is chosen from their address by its position in it (mars-places.js).")
    print("/* eslint-disable prettier/prettier */")
    print(f"export const MAP_BOX = {{ width: {W}, height: {H}, spotY: {SPOT_Y} }};")
    print("export const PLACES = [")
    print("\n".join(rows))
    print("];")


if __name__ == "__main__":
    main()
